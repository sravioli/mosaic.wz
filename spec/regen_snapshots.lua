-- Rewrite spec/fixtures/snapshots.lua from the current renderer.
-- Only for intentional visual changes: run from the repo root with
--   lua5.4 spec/regen_snapshots.lua
-- and explain the change in the commit.
local wezterm = dofile "spec/mocks/wezterm.lua"
package.path = "plugin/?.lua;plugin/?/init.lua;" .. package.path
local scenarios = dofile "spec/support/scenarios.lua"
local config = dofile "spec/support/config.lua"

local out = assert(io.open("spec/fixtures/snapshots.lua", "w"))
out:write "-- Generated by spec/regen_snapshots.lua. Do not edit.\nreturn {\n"
for _, s in ipairs(scenarios.list) do
  for k in pairs(package.loaded) do
    if k:match "^mosaic" then
      package.loaded[k] = nil
    end
  end
  wezterm._handlers = {}
  local mosaic = require "mosaic.api"
  mosaic.setup(config(mosaic, scenarios.hints))
  local window, pane = scenarios.build(s)
  for i, w in ipairs(s.tabs) do
    mosaic.budget.record(i - 1, w)
  end
  mosaic.budget.set_count(#s.tabs)
  mosaic.refresh(window, pane)
  out:write(
    ("  [%q] = { left = %q, right = %q },\n"):format(
      s.name,
      window._left or "",
      window._right or ""
    )
  )
end
out:write "}\n"
out:close()

-- Tabs: powerline preset with the default title.
local tabs = dofile "spec/support/tabs.lua"
local tout = assert(io.open("spec/fixtures/tabs.lua", "w"))
tout:write "-- Generated by spec/regen_snapshots.lua. Do not edit.\nreturn {\n"
for k in pairs(package.loaded) do
  if k:match "^mosaic" then
    package.loaded[k] = nil
  end
end
wezterm._handlers = {}
local mosaic = require "mosaic.api"
mosaic.setup { preset = "powerline" }
mosaic.apply_to_config {}
local format = wezterm._handlers["format-tab-title"][1]
for _, s in ipairs(tabs.list) do
  local out = format(s.tab, { s.tab, {}, {} }, nil, tabs.config, s.hover, s.width)
  tout:write(("  [%q] = %q,\n"):format(s.name, out))
end
tout:write "}\n"
tout:close()
